/** Every code this mapping understands; anything else is genuinely unknown. */
export const SOURCE_IMPORT_FAILURE_CODES = Object.keys(FAILURE_MESSAGES);

/** Short heading per group; the per-file sentence keeps the specific next step. */
const GROUP_LABELS: Record<SourceImportFailureGroup, Bilingual> = {
  component: ['安装或组件问题', 'Installation or component problem'],
  parser: ['文件解析失败', 'The file could not be read'],
  timeout: ['处理超时', 'Timed out'],
  size: ['超过导入限制', 'Over the import limit'],
  network: ['网络或地址问题', 'Network or address problem'],
  content: ['网页内容无法抓取', 'Page content unavailable'],
  local: ['本机存储问题', 'Local storage problem'],
  canceled: ['已取消', 'Cancelled'],
  other: ['其他原因', 'Other reasons'],
};

/** Reserved for codes this build does not know; keep it distinct from every mapped code. */
const FALLBACK: FailureMessage = [
  'other',
  '读取资料失败，可在任务详情查看原因或重试。',
  'The document could not be read. See activity details or retry.',
];

/** The group a stored code belongs to; codes this build does not know are `other`. */
const UNKNOWN_GROUP: SourceImportFailureGroup = 'other';

function entryFor(code: string): FailureMessage | null {
  return Object.prototype.hasOwnProperty.call(FAILURE_MESSAGES, code)
    ? FAILURE_MESSAGES[code]
    : null;
}

/**
 * Maps a `source_jobs.error_code` to a bilingual sentence. Unknown codes keep the
 * generic fallback, while the raw code stays visible in the caller's `title`.
 */
export function sourceImportFailure(code: string, t: Translate): string {
  const message = entryFor(code) ?? FALLBACK;
  return t(message[1], message[2]);
}

/**
 * Which group a stored code belongs to. A job cancelled by the user carries
 * `canceled`, so it stays out of the failure wording but still shows in the
 * summary; a code from a newer build lands in `other` instead of being dropped.
 */
export function sourceImportFailureGroup(
  code: string | null | undefined,
): SourceImportFailureGroup {
  if (typeof code !== 'string') return UNKNOWN_GROUP;
  return entryFor(code)?.[0] ?? UNKNOWN_GROUP;
}

/** The short heading for one group, in the active language. */
export function sourceImportFailureGroupLabel(
  group: SourceImportFailureGroup,
  t: Translate,
): string {
  const label = GROUP_LABELS[group] ?? GROUP_LABELS.other;
  return t(label[0], label[1]);
}

/**
 * Bundles records the caller already knows failed, most actionable group first.
 * A group only appears when it holds a record, and the records inside it keep the
 * order the caller passed, so the panel stays stable while a batch finishes.
 */
export function groupImportFailures<T>(
  records: readonly T[],
  groupOf: (record: T) => SourceImportFailureGroup,
): { group: SourceImportFailureGroup; count: number; records: T[] }[] {
  const buckets = new Map<SourceImportFailureGroup, T[]>();
  for (const record of records) {
    const group = groupOf(record);
    const bucket = buckets.get(group);
    if (bucket) bucket.push(record);
    else buckets.set(group, [record]);
  }
  return SOURCE_IMPORT_FAILURE_GROUPS.flatMap((group) => {
    const bucket = buckets.get(group);
    return bucket ? [{ group, count: bucket.length, records: bucket }] : [];
  });
}

/**
 * One bundled line for the activity panel or the import banner, e.g.
 * `3 项未完成：安装或组件 2 · 解析失败 1`. Empty when nothing failed, so callers
 * can render it unconditionally.
 */
export function importFailureSummary(
  groups: readonly { group: SourceImportFailureGroup; count: number }[],
  t: Translate,
): string {
  const total = groups.reduce((sum, entry) => sum + entry.count, 0);
  if (total === 0) return '';
  const parts = (index: 0 | 1) =>
    groups
      .map((entry) => `${(GROUP_LABELS[entry.group] ?? GROUP_LABELS.other)[index]} ×${entry.count}`)
      .join(' · ');
  return t(
    `${total} 项未完成：${parts(0)}`,
    `${total} ${total === 1 ? 'item' : 'items'} did not complete: ${parts(1)}`,
  );
}

/**
 * The line the startup banner and the diagnostics page show for a parse component
 * this installation cannot use.
 *
 * A missing component is an environment fact the user has to repair, so the line
 * names the exact path the application looked for and keeps the next step of the
 * shared sentence instead of leaving a bare path or a bare code on screen.
 */
export function parseComponentNotice(
  issue: { code: string; path: string | null },
  t: Translate,
): string {
  const detail = sourceImportFailure(issue.code, t);
  if (!issue.path) return detail;
  return t(
    `解析组件 ${issue.path} 不可用。${detail}`,
    `Parse component ${issue.path} is unavailable. ${detail}`,
  );
}
