/**
 * The wording for a failed source import. The core only reports machine codes, so
 * every code this chain can produce is mapped here to an actionable bilingual
 * message: the webpage capture (`crates/pkms-app/src/webpage_capture.rs`), the
 * parse worker (`crates/pkms-worker/src/{pdf,html,docx,lib}.rs`, surfaced through
 * `crates/pkms-app/src/source_process.rs`) and the core job pipeline
 * (`crates/pkms-app/src/error_codes.rs`, `crates/pkms-app/src/source_background.rs`,
 * `crates/pkms-core/src/source_jobs.rs`).
 * The caller keeps showing the raw code in the element's `title`, so a code that
 * is not mapped here is still diagnosable instead of being silently swallowed.
 * Each entry also carries the group the activity panel bundles it under, so the
 * grouping and the wording can never contradict each other.
 */

type Translate = (zh: string, en: string) => string;
type Bilingual = readonly [zh: string, en: string];

/**
 * How a failure is bundled for the user: the grouping answers "what do I do next"
 * rather than "which component reported this". It lets the panel say
 * `3 项未完成：安装或组件 2 · 已取消 1` instead of repeating three near-identical
 * sentences. This order is the reading order of that summary: problems only the
 * user can repair first, the user's own cancellation last.
 */
